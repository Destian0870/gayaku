#!/usr/bin/env python3
"""Generate flutter_app/lib/logic/garment_labels.dart from the class list and labels.json.

The class list (`artifacts/classes.json`) is written by `prepare_data.py` and holds the
classifier's output order: `labels[i]` is the label the model's score `i` refers to. The
generated Dart file mirrors that order, so regenerating it is what keeps the app and the
exported model in step (see ml_workspace/README.md).

    python ml_workspace/scripts/gen_dart_labels.py            # writes the Dart file
    python ml_workspace/scripts/gen_dart_labels.py --check     # fails if it is stale

Exits non-zero when a label in the class list has no entry in labels.json, or when an
entry cannot be resolved to one of the five Categories.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CATEGORIES = ("Tops", "Bottoms", "Outerwear", "Shoes", "Accessories")

HEADER = "// GENERATED by ml_workspace/scripts/gen_dart_labels.py -- do not edit by hand.\n"
CATEGORIES_DOC = "/// Class order of the exported classifier; scores[N] matches garmentCategories[N].\n"
CATEGORY_DOC = (
    "/// Model label -> one of the five Categories "
    "(Tops, Bottoms, Outerwear, Shoes, Accessories).\n"
)
NAME_DOC = "/// Model label -> Indonesian display name shown in the scanner's name row.\n"


class CodegenError(Exception):
    """Anything that makes the generated file untrustworthy."""


def read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise CodegenError(f"{path} does not exist") from exc
    except json.JSONDecodeError as exc:
        raise CodegenError(f"{path} is not valid JSON: {exc}") from exc


def class_labels(classes_doc: dict, classes_path: Path) -> list[str]:
    labels = classes_doc.get("labels")
    if not isinstance(labels, list) or not labels:
        raise CodegenError(f"{classes_path}: expected a non-empty 'labels' list")
    for label in labels:
        if not isinstance(label, str) or not label:
            raise CodegenError(f"{classes_path}: bad class entry {label!r}")
    duplicates = sorted({label for label in labels if labels.count(label) > 1})
    if duplicates:
        raise CodegenError(f"{classes_path}: duplicated classes {duplicates}")
    return labels


def label_index(labels_doc: dict, labels_path: Path) -> dict[str, dict]:
    """Map every catalogue label to its Category/name, rejecting contradictory rows."""
    entries = labels_doc.get("labels")
    if not isinstance(entries, list) or not entries:
        raise CodegenError(f"{labels_path}: expected a non-empty 'labels' list")
    index: dict[str, dict] = {}
    for entry in entries:
        try:
            label, category, name = entry["label"], entry["category"], entry["name"]
        except (TypeError, KeyError) as exc:
            raise CodegenError(f"{labels_path}: malformed entry {entry!r}") from exc
        if not isinstance(name, str) or not name:
            raise CodegenError(f"{labels_path}: {label!r} has no display name")
        previous = index.get(label)
        if previous and (previous["category"], previous["name"]) != (category, name):
            raise CodegenError(
                f"{labels_path}: {label!r} maps to both "
                f"({previous['category']}, {previous['name']!r}) and ({category}, {name!r}); "
                "labels shared by two datasets must agree"
            )
        index[label] = {"category": category, "name": name}
    return index


def resolve(classes: list[str], index: dict[str, dict]) -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    missing = [label for label in classes if label not in index]
    if missing:
        raise CodegenError(
            "no entry in labels.json for classifier classes: "
            + ", ".join(repr(label) for label in missing)
            + " -- add them to ml_workspace/labels.json (keep:true) and rerun"
        )
    for label in classes:
        entry = index[label]
        if entry["category"] not in CATEGORIES:
            raise CodegenError(
                f"{label!r} maps to {entry['category']!r}; a classifier class must map to one "
                f"of {', '.join(CATEGORIES)}"
            )
        rows.append((label, entry["category"], entry["name"]))
    return rows


def dart_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("$", "\\$")
        .replace("\n", "\\n")
    )
    return f"'{escaped}'"


def render(rows: list[tuple[str, str, str]]) -> str:
    categories = "".join(f"  {dart_string(label)},\n" for label, _, _ in rows)
    category_map = "".join(
        f"  {dart_string(label)}: {dart_string(category)},\n" for label, category, _ in rows
    )
    name_map = "".join(
        f"  {dart_string(label)}: {dart_string(name)},\n" for label, _, name in rows
    )
    return (
        HEADER
        + CATEGORIES_DOC
        + "const garmentCategories = <String>[\n"
        + categories
        + "];\n"
        + CATEGORY_DOC
        + "const garmentLabelCategory = <String, String>{\n"
        + category_map
        + "};\n"
        + NAME_DOC
        + "const garmentLabelName = <String, String>{\n"
        + name_map
        + "};\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--classes",
        type=Path,
        default=REPO_ROOT / "ml_workspace" / "artifacts" / "classes.json",
        help="class list written by prepare_data.py (default: %(default)s)",
    )
    parser.add_argument(
        "--labels",
        type=Path,
        default=REPO_ROOT / "ml_workspace" / "labels.json",
        help="semantic label table (default: %(default)s)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=REPO_ROOT / "flutter_app" / "lib" / "logic" / "garment_labels.dart",
        help="generated Dart file (default: %(default)s)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 2 if the file on disk differs from the generator's output",
    )
    args = parser.parse_args(argv)

    try:
        rows = resolve(
            class_labels(read_json(args.classes), args.classes),
            label_index(read_json(args.labels), args.labels),
        )
    except CodegenError as exc:
        print(f"gen_dart_labels: {exc}", file=sys.stderr)
        return 1

    generated = render(rows)
    if args.check:
        try:
            current = args.out.read_text(encoding="utf-8")
        except FileNotFoundError:
            current = None
        if current != generated:
            print(f"gen_dart_labels: {args.out} is stale; rerun without --check", file=sys.stderr)
            return 2
        print(f"gen_dart_labels: {args.out} matches ({len(rows)} classes)")
        return 0

    try:
        current = args.out.read_text(encoding="utf-8")
    except FileNotFoundError:
        current = None
    if current == generated:
        print(f"gen_dart_labels: {args.out} already up to date ({len(rows)} classes)")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generated, encoding="utf-8", newline="\n")
    print(f"gen_dart_labels: wrote {args.out} ({len(rows)} classes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
